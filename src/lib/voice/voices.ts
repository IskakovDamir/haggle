/** The clip for a voice in a language: "/voices/male.mp3" or "/voices/male-es.mp3". */
export function voicePreviewPathFor(voice: AgentVoice, language: "en" | "es"): string {
  return language === "es" ? `/voices/${voice}-es.mp3` : voicePreviewPath(voice);
}

/** Where a voice's preview clip is served from, under public/. */
export function voicePreviewPath(voice: AgentVoice): string {
  return `/voices/${voice}.mp3`;
}
