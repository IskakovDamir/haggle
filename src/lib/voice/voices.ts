// The two voices a visitor can pick for the agent. Voice ids are public identifiers, not secrets.
// Both come from the ElevenLabs voice library, which needs a paid plan (Starter or above):
//   Hope: conversational, with natural "mm"s, pauses and small laughs
//   Jack: a natural, upbeat customer-support voice, early 30s
// On the free plan, swap back to default voices such as Sarah (EXAVITQu4vr4xnSDxMaL) and Chris (iP95p4xoKVk53GoZ742B).

export type AgentVoice = "female" | "male";

export const AGENT_VOICES: Record<AgentVoice, { id: string; name: string; label: string }> = {
  female: { id: "uYXf8XasLslADfZ2MB4u", name: "Hope", label: "Female" },
  male: { id: "7EzWGsX10sAS4c9m9cPf", name: "Jack", label: "Male" },
};

export const DEFAULT_AGENT_VOICE: AgentVoice = "female";

/** The voices for a call held in Spanish: native Latin American speakers from the voice library. */
export const SPANISH_AGENT_VOICES: Record<AgentVoice, { id: string; name: string }> = {
  female: { id: "kcQkGnn0HAT2JRDQ4Ljp", name: "Norah" },
  male: { id: "htFfPSZGJwjBv1CL0aMD", name: "Antonio" },
};

/** The voice that speaks a call: the picked voice, or its Spanish counterpart on a call in Spanish. */
export function spokenVoiceId(pickedVoiceId: string | undefined, language: "en" | "es" | undefined): string | undefined {
  if (!pickedVoiceId || language !== "es") return pickedVoiceId;
  const picked = (Object.keys(AGENT_VOICES) as AgentVoice[]).find((voice) => AGENT_VOICES[voice].id === pickedVoiceId);
  return picked ? SPANISH_AGENT_VOICES[picked].id : pickedVoiceId;
}

